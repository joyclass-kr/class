    window.COMPUTER_REVIEWED_QUESTIONS = finalReviewedQuestions;

    finalReviewedQuestions.forEach(([lessonId, questionIndex, question]) => {
        const target = window.COMPUTER_FOUNDATION_LESSONS.find((lesson) => lesson.id === lessonId);
        if (target?.questions?.[questionIndex]) target.questions[questionIndex] = question;
    });
