                <p>코가 길어진다는 생각이 우스운 까닭은, 코가 얼굴에서 가장 눈에 띄면서도 마음대로 할 수 없는 곳이기 때문이에요. 옛이야기는 이렇게 몸의 한 군데를 크게 부풀려 웃음을 만들곤 한답니다.</p>
