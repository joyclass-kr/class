const HAS_HISTORY = typeof HISTORY !== 'undefined';
const HS = () => ((LANG === 'en' && EN.history) ? EN.history : HISTORY);

// 「1장 · 」이든 「Chapter 1 · 」이든 앞머리를 뗀다.
const bareTitle = t => t.replace(/^(\d+장|Chapter \d+) · /, '');


function artFrame(src, emoji) {
    return `
        <div class="art-frame">
            <img src="images/${src}" alt="" onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';">
            <div class="art-fallback" style="display:none">${emoji}</div>
        </div>`;
}

function coverToc() {
    const item = s => `
        <button type="button" data-goto="${s.num}">
            <span class="toc-num">${s.num}</span>
            <span>${bareTitle(s.title)}</span>
        </button>`;
    return `
        <nav class="cover-toc">
            <h2>${T().toc}</h2>
            ${CH().map(item).join('')}
            <button type="button" data-goto-kind="quiz">
                <span class="toc-num">❓</span>
                <span>${T().quiz}</span>
            </button>
        </nav>`;
}

function coverPage() {
    const c = CV();
    return `
        <div class="page page-cover">
            <div class="story-page-left story-page-left-full">
                ${artFrame(c.art || COVER.art, c.emoji)}
                ${readBtnHtml()}
            </div>
            <div class="story-page-right">
                <h1 data-say="0">${c.title}</h1>
                ${c.intro.map((t, i) => `<p data-say="${i + 1}">${t}</p>`).join('')}
                ${coverToc()}
            </div>
        </div>`;
}

