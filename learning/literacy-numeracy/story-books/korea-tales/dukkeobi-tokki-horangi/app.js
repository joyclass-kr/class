function coverToc() {
    const item = s => `
        <button type="button" data-goto="${s.num}">
            <span class="toc-num">${s.num}</span>
            <span>${bareTitle(s.title)}</span>
        </button>`;
    return `
        <nav class="cover-toc">
            <h2>${T().toc}</h2>
            ${CH().map(item).join('')}
            <button type="button" data-goto-kind="quiz">
                <span class="toc-num">❓</span>
                <span>${T().quiz}</span>
            </button>
        </nav>`;
}

