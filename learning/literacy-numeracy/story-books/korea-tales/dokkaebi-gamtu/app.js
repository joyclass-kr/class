function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'spread':
            return spreadPage(page.chapter, page.beat, page.isFirst);
        case 'after':
            return afterPage({ ...page.spread, last: page.last }, page.isFirst);
        case 'history':
            return historyPage();
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

