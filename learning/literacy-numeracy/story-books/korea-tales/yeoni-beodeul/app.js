                <p>바위 문을 열면 그 안에 봄이 들어 있다는 생각은 우리 옛이야기에 자주 나와요. 겨울이 아무리 길어도 어딘가에 봄이 갇혀 있을 뿐이라고 여긴 것이지요.</p>
