import fs from 'node:fs';
import path from 'node:path';

const lessonDir = path.join(import.meta.dirname, 'hanja-lessons');
const sources = fs.readdirSync(lessonDir)
  .filter((name) => name.endsWith('.json'))
  .flatMap((name) => JSON.parse(fs.readFileSync(path.join(lessonDir, name), 'utf8')));
const sourceMap = new Map(sources.flatMap((lesson) => lesson.characters.map((item) => [item.character, item])));
const vocabMap = new Map();
for (const lesson of sources) {
  for (const question of lesson.questions ?? []) {
    for (const option of question.options ?? []) {
      if (option.term && option.hanja) {
        vocabMap.set(option.term, {
          term: option.term,
          hanja: option.hanja,
          sentence: (option.sentence || `${option.term}의 뜻과 쓰임을 문맥에서 확인했습니다.`)
            .replaceAll('{{', '').replaceAll('}}', '')
        });
      }
    }
  }
}

