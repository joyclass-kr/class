const allRecords = () => [...vocabMap.values()];
function targetItems(character, reading) {
  if (manual[character]) return manual[character].slice(0, 3);
  const source = sourceMap.get(character);
  const preferred = (source?.words ?? []).map((term,index) => vocabMap.get(term) || (supplementHanja[character]?.[index] ? {term,hanja:supplementHanja[character][index],sentence:source.explanation} : null)).filter(Boolean);
  const matching = allRecords().filter((item) => item.hanja.includes(character));
  const unique = [...new Map([...preferred, ...matching].map((item) => [item.term, item])).values()];
  if (unique.length < 3) throw new Error(`${character}(${reading}) target examples: ${unique.length}`);
  return unique.slice(0, 3);
}

function distractor(character, reading, used) {
  if (manual[character]?.[3]) return manual[character][3];
  const candidate = allRecords().find((item) =>
    item.term.includes(reading) && !item.hanja.includes(character) && !used.has(item.term));
  if (!candidate && manualDistractor[character]) return manualDistractor[character];
  if (!candidate) throw new Error(`${character}(${reading}) has no distractor`);
  return candidate;
}

const lessons = groups.map((term) => {
  const characters = [...term].map((character) => {
    const item = meta[character];
    if (!item) throw new Error(`Missing metadata: ${character}`);
    return {
      character,
      reading: item.sounds.join('·'),
      meaning: item.hun,
      hunEum: item.sounds.map((eum) => ({ hun: item.hun, eum })),
      explanation: item.explanation,
      examples: targetItems(character, item.sounds[0]).map(({ term: word, hanja, sentence }) => [word, hanja, sentence])
    };
  });
  const questions = characters.map(({ character, reading, examples }) => {
    const primaryReading = reading.split('·')[0];
    const used = new Set(examples.map(([word]) => word));
    const miss = distractor(character, primaryReading, used);
    const options = [
      ...examples.map(([word, hanja, sentence]) => [word, hanja, sentence.replace(word, `{{${word}}}`)]),
      [miss.term, miss.hanja, miss.sentence.replace(miss.term, `{{${miss.term}}}`)]
    ];
    return {
      target: character,
      answer: 3,
      note: `${examples.map(([word, hanja]) => `${word}(${hanja})`).join('·')}에는 ${character} 글자가 쓰입니다. ${miss.term}(${miss.hanja})에는 쓰이지 않습니다.`,
      options
    };
  });
  return {
    term,
    reading: characters.map((item) => item.reading).join(' · '),
    theme: characters.map((item) => item.meaning).join(' · '),
    characters,
    questions
  };
});

for (const lesson of lessons) {
  for (const character of lesson.characters) {
    if (character.character === '長') character.hunEum = [{ hun: '길', eum: '장' }, { hun: '어른', eum: '장' }];
    if (character.character === '車') character.examples.push(['거마', '車馬', '옛 기록에서는 수레와 말을 아울러 거마라고 불렀습니다.']);
  }
}

